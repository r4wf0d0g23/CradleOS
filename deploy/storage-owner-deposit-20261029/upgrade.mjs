// One-shot compatible upgrade only. No SSU/configuration/asset operations.
import {createRequire} from 'node:module';
import {readFileSync,writeFileSync,existsSync,openSync,writeSync,fsyncSync,closeSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../../cradleos-dapp/package.json',import.meta.url));
const {SuiGrpcClient,GrpcTypes}=require('@mysten/sui/grpc');
const {Transaction}=require('@mysten/sui/transactions');
const {Ed25519Keypair}=require('@mysten/sui/keypairs/ed25519');
const {verifyPersonalMessageSignature}=require('@mysten/sui/verify');
const dir=new URL('./',import.meta.url),root=new URL('../../',dir);
const read=n=>JSON.parse(readFileSync(new URL(n,dir)));
const save=(n,v)=>writeFileSync(new URL(n,dir),JSON.stringify(v,(_,v)=>typeof v==='bigint'?v.toString():v,2)+'\n');
const publisher='0x177583b2ee07dc6ce8056e49fda83637c996b9143adf651a8de5ebe03699b91a';
const original='0xb373fbf3bc4236e92494214fe5a57a8e95b62bb0efd6262023daa3d60d86401f';
const capId='0xe0fe0b530e1f46c6140bc8105bd4476392133694b2ac48854da7e743cef7b653';
const build=read('package-build.json');
assert.equal(createHash('sha256').update(readFileSync(new URL('cradleos_storage_access/sources/storage_access.move',root))).digest('hex'),read('package-checks.json').sourceSHA256);
assert.equal(build.modules.length,1);
assert.equal(build.dependencies.filter(p=>!/^0x0+[12]$/.test(p)).join(','),'0x7be18d6294e533bedd9a5d70a96ce8d9d4b87a7c74188ba65d3fe966bbed9d92');
assert.equal(createHash('sha256').update(Buffer.from(build.modules[0],'base64')).digest('hex'),read('package-checks.json').bytecodeSHA256);
assert.ok(!existsSync(new URL('upgrade-pending.json',dir))&&!existsSync(new URL('upgrade.json',dir)),'Reconcile prior attempt; never blindly retry.');
const c=new SuiGrpcClient({network:'testnet',baseUrl:'https://fullnode.testnet.sui.io:443'});
assert.equal((await c.core.getChainIdentifier()).chainIdentifier,'69WiPg3DAQiwdxfncX6wYQ2siKwAe6L9BZthQea3JNMD');
const cap=GrpcTypes.Object.toJson((await c.ledgerService.getObject({objectId:capId,readMask:{paths:['object_id','owner','json','object_type']}})).response.object);
assert.equal(cap.owner.kind,'ADDRESS');assert.equal(cap.owner.address,publisher);
assert.equal(cap.json.package,original);assert.equal(cap.json.version,'1');assert.equal(cap.json.policy,0);
const tx=new Transaction();tx.setSender(publisher);tx.setGasBudget(500000000);
const [ticket]=tx.moveCall({target:'0x2::package::authorize_upgrade',arguments:[tx.object(capId),tx.pure.u8(0),tx.pure.vector('u8',build.digest)]});
const receipt=tx.upgrade({modules:build.modules,dependencies:build.dependencies,package:original,ticket});
tx.moveCall({target:'0x2::package::commit_upgrade',arguments:[tx.object(capId),receipt]});
const bytes=await tx.build({client:c});
const sim=await c.core.simulateTransaction({transaction:bytes,checksEnabled:true,include:{effects:true,objectTypes:true}});
save(process.env.STORAGE_UPGRADE_SIGN==='1'?'final-upgrade-simulation.json':'upgrade-simulation.json',sim);
assert.ok(sim.Transaction?.status?.success,'Compatible upgrade simulation failed');
if(process.env.STORAGE_UPGRADE_SIGN!=='1'){console.log(JSON.stringify({simulation:true,signed:false,compatible:true}));process.exit(0);}
const custody=read('custody.json'),proof=read('restored-signing-proof.json');
assert.equal(custody.publisher,publisher);assert.equal(custody.upgradeCap,capId);assert.equal(custody.upgradeCapOwner,publisher);assert.equal(custody.operatorMessage,'1565366765733675169');
assert.ok(proof.restoredFromBackup&&!proof.transactionSubmitted);
assert.ok(Date.now()-Date.parse(proof.checkedAt)>=0&&Date.now()-Date.parse(proof.checkedAt)<3600000);
assert.equal((await verifyPersonalMessageSignature(Buffer.from(proof.challengeBase64,'base64'),proof.signature)).toSuiAddress(),publisher);assert.equal(custody.backupProof,proof.digestHex);
const git=(...args)=>execFileSync('git',args,{cwd:root,encoding:'utf8'}).trim();
assert.equal(git('status','--porcelain','--untracked-files=no'),'');
const source=git('rev-parse','HEAD');assert.equal(git('rev-parse','upgrade/cradleos-storage-owner-deposit-2026-10-29'),source);
assert.deepEqual(build,read('fresh-build.json'));
const journal=openSync(new URL('upgrade-pending.json',dir),'wx',0o600);
let signer;
try{for(const k of JSON.parse(readFileSync('/home/rawdata/.sui/sui_config/sui.keystore','utf8'))){const b=Buffer.from(k,'base64');if(b.length===33&&b[0]===0){const s=Ed25519Keypair.fromSecretKey(b.subarray(1));if(s.toSuiAddress()===publisher)signer=s;}}assert.ok(signer);}catch{closeSync(journal);throw Error('Publisher unavailable; secret-bearing details suppressed');}
const signed=await signer.signTransaction(bytes),digest=await tx.getDigest();
writeSync(journal,JSON.stringify({digest,source,transactionBytes:Buffer.from(bytes).toString('base64'),signature:signed.signature}));fsyncSync(journal);closeSync(journal);const directory=openSync(dir,'r');fsyncSync(directory);closeSync(directory);
const result=await c.core.executeTransaction({transaction:bytes,signatures:[signed.signature],include:{effects:true,objectTypes:true}});
save('upgrade.json',result);assert.equal(result.Transaction?.digest,digest);assert.ok(result.Transaction?.status?.success,'Upgrade not successful; reconcile');
console.log(JSON.stringify({digest,source,success:true,receipt:'upgrade.json'}));
